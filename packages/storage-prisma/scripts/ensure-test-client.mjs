import { createHash } from "node:crypto";
import { spawn } from "node:child_process";
import { mkdir, readFile, readdir, rename, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const packageDirectory = dirname(scriptDirectory);
const schemaPath = join(packageDirectory, "__test__", "schema.prisma");
const generatedDirectory = join(packageDirectory, "__test__", "generated");
const statePath = join(generatedDirectory, ".time-fit-client-state.json");
const lockPath = join(tmpdir(), `time-fit-storage-prisma-${shortSha256(packageDirectory)}.lock`);
const lockTimeoutMilliseconds = 60_000;

await ensureStoragePrismaTestClient();

async function ensureStoragePrismaTestClient() {
  const expectedState = await readExpectedTestClientState();
  if (await isCurrentStoragePrismaTestClient(expectedState)) {
    console.log("Storage Prisma test client is current.");
    return;
  }

  const ownsLock = await acquireTestClientGenerationLock(expectedState);
  if (!ownsLock) {
    console.log("Storage Prisma test client was generated by another run.");
    return;
  }

  try {
    if (!await isCurrentStoragePrismaTestClient(expectedState)) {
      await generateStoragePrismaTestClient();
      await writeTestClientState(expectedState);
    }
  } finally {
    await rm(lockPath, { recursive: true, force: true });
  }
}

async function readExpectedTestClientState() {
  const [schema, clientPackage] = await Promise.all([
    readFile(schemaPath, "utf8"),
    readFile(require.resolve("@prisma/client/package.json"), "utf8"),
  ]);
  return Object.freeze({ schemaHash: sha256(schema), prismaClientVersion: JSON.parse(clientPackage).version });
}

async function isCurrentStoragePrismaTestClient(expectedState) {
  const state = await readJsonIfPresent(statePath);
  if (JSON.stringify(state) !== JSON.stringify(expectedState)) return false;
  const files = await readDirectoryIfPresent(generatedDirectory);
  return files.includes("index.js") && files.some((file) => file.startsWith("libquery_engine-"));
}

async function acquireTestClientGenerationLock(expectedState) {
  const deadline = Date.now() + lockTimeoutMilliseconds;
  while (Date.now() < deadline) {
    try {
      await mkdir(lockPath);
      return true;
    } catch (error) {
      if (error?.code !== "EEXIST") throw error;
      if (await isCurrentStoragePrismaTestClient(expectedState)) return false;
      await wait(100);
    }
  }
  throw new Error(`Timed out waiting for the Prisma test client generation lock at ${lockPath}`);
}

async function readJsonIfPresent(path) {
  try {
    return JSON.parse(await readFile(path, "utf8"));
  } catch (error) {
    if (error?.code === "ENOENT") return null;
    throw error;
  }
}

async function readDirectoryIfPresent(path) {
  try {
    return await readdir(path);
  } catch (error) {
    if (error?.code === "ENOENT") return [];
    throw error;
  }
}

async function generateStoragePrismaTestClient() {
  await new Promise((resolve, reject) => {
    const command = process.platform === "win32" ? "yarn.cmd" : "yarn";
    const childProcess = spawn(command, ["prisma", "generate", "--schema", "__test__/schema.prisma"], {
      cwd: packageDirectory,
      stdio: "inherit",
    });
    childProcess.once("error", reject);
    childProcess.once("exit", (code) => code === 0 ? resolve() : reject(new Error(`prisma generate exited with code ${code}`)));
  });
}

async function writeTestClientState(state) {
  const temporaryStatePath = `${statePath}.${process.pid}.tmp`;
  await writeFile(temporaryStatePath, `${JSON.stringify(state)}\n`, "utf8");
  await rename(temporaryStatePath, statePath);
}

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

function shortSha256(value) {
  return sha256(value).slice(0, 16);
}

function wait(milliseconds) {
  return new Promise((resolve) => setTimeout(resolve, milliseconds));
}
